// Local QA only. Pass an installed Playwright index.mjs path; does not use Chrome.
import {pathToFileURL} from 'node:url'
import {resolve} from 'node:path'
import {mkdir,writeFile} from 'node:fs/promises'
import assert from 'node:assert/strict'
const {firefox}=await import(pathToFileURL(resolve(process.argv[2])).href)
const browser=await firefox.launch({headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true,reducedMotion:'reduce'})
let page=await context.newPage();const errors=[]
page.setDefaultTimeout(20000)
page.on('pageerror',error=>errors.push(error.message))
const root=resolve('kits/brand-delivery-kit'),out=resolve('.tmp/brand-review')
const galleryUrl=process.argv[3]||pathToFileURL(resolve(root,'index.html')).href
await mkdir(out,{recursive:true})
try{
 await page.goto(galleryUrl)
 await page.waitForFunction(()=>document.querySelectorAll('.template-card').length===36)
 assert.equal(await page.locator('#template-list button').count(),0)
 assert.equal(await page.locator('.template-card img').count(),36)
 assert.match(await page.locator('script[src*="assets/editor-"]').getAttribute('src'),/editor-[a-f0-9]{12}\.js$/)
 await page.screenshot({path:resolve(out,'ui-desktop-v3.png')})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await page.locator('.template-card img').evaluateAll(images=>images.forEach(img=>img.loading='eager'))
 await page.waitForFunction(()=>[...document.querySelectorAll('.template-card img')].every(img=>img.complete&&img.naturalWidth>0))
 await page.evaluate(()=>scrollTo(0,document.getElementById('collection').offsetTop+30))
 await page.screenshot({path:resolve(out,'ui-all-designs-v3.png')})
 await page.locator('.template-card').last().scrollIntoViewIfNeeded()
 assert.equal(await page.locator('.template-card').last().locator('img').evaluate(img=>img.naturalWidth>0),true)
 await page.locator('#category').scrollIntoViewIfNeeded()
 await page.selectOption('#category','Ads')
 await page.locator('#category').scrollIntoViewIfNeeded()
 await page.locator('.template-card img').evaluateAll(images=>images.forEach(img=>img.loading='eager'))
 await page.waitForFunction(()=>[...document.querySelectorAll('.template-card img')].every(img=>img.complete&&img.naturalWidth>0))
 assert.equal(await page.locator('.template-card').count(),6)
 await page.screenshot({path:resolve(out,'ui-gallery-v3.png')})
 await page.locator('#open-settings').click()
 await page.locator('#field-name').fill('Cedar & Clay')
 await page.locator('#field-cta').fill('See the collection')
 await page.locator('#done-settings').click()
 await page.locator('.template-card').first().click()
 assert.ok((await page.locator('#artwork').textContent()).includes('Cedar & Clay'))
 await page.screenshot({path:resolve(out,'ui-preview-v3.png')})
 const pngPromise=page.waitForEvent('download')
 await page.locator('#download-png').click()
 const png=await pngPromise;await png.saveAs(resolve(out,'browser-export-ad-square.png'))
 assert.equal(png.suggestedFilename(),'cedar-clay-ad-square.png')
 const svgPromise=page.waitForEvent('download');await page.locator('#download-svg').click();const svg=await svgPromise;await svg.saveAs(resolve(out,'browser-export-ad-square.svg'))
 await page.keyboard.press('Escape');assert.equal(await page.locator('#preview-dialog').isHidden(),true)
 const zipPromise=page.waitForEvent('download');await page.locator('#export-pack').click();const zip=await zipPromise;await zip.saveAs(resolve(out,'browser-custom-export.zip'))
 console.log('Desktop gallery and real PNG/SVG/ZIP downloads passed.')
 await context.close()
 const mobile=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'})
 page=await mobile.newPage();page.setDefaultTimeout(20000);page.on('pageerror',error=>errors.push(error.message))
 await page.goto(galleryUrl)
 await page.waitForFunction(()=>document.querySelectorAll('.template-card').length===36)
 await page.screenshot({path:resolve(out,'ui-mobile-v3.png'),timeout:20000})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await page.locator('#category').scrollIntoViewIfNeeded();await page.screenshot({path:resolve(out,'ui-mobile-gallery-v3.png')})
 await page.locator('.template-card').first().click();await page.screenshot({path:resolve(out,'ui-mobile-preview-v3.png')})
 await page.keyboard.press('Escape');await page.locator('#open-settings').click()
 const first=page.locator('#close-settings'),last=page.locator('#done-settings')
 await first.focus();await page.keyboard.press('Shift+Tab');assert.equal(await last.evaluate(el=>el===document.activeElement),true)
 await page.keyboard.press('Tab');assert.equal(await first.evaluate(el=>el===document.activeElement),true)
 await page.keyboard.press('Escape')
 await page.goto(new URL('START-HERE.html',galleryUrl).href);assert.equal(await page.locator('h1').textContent(),'A good place to start.')
 assert.equal(await page.evaluate(()=>[...document.images].some(i=>!i.complete||!i.naturalWidth)),false)
 await page.screenshot({path:resolve(out,'ui-start-guide-v3.png'),fullPage:true})
 assert.deepEqual(errors,[])
 const staticContext=await browser.newContext({viewport:{width:1440,height:1050},javaScriptEnabled:false,reducedMotion:'reduce'})
 const staticPage=await staticContext.newPage();staticPage.setDefaultTimeout(20000)
 await staticPage.goto(galleryUrl)
 assert.equal(await staticPage.locator('.template-card img').count(),36)
 await staticPage.locator('.template-card img').evaluateAll(images=>images.forEach(img=>img.loading='eager'))
 await staticPage.waitForFunction(()=>[...document.querySelectorAll('.template-card img')].every(img=>img.complete&&img.naturalWidth>0))
 await staticPage.evaluate(()=>scrollTo(0,document.getElementById('collection').offsetTop+30))
 await staticPage.screenshot({path:resolve(out,'ui-gallery-without-js.png')})
 await staticPage.locator('.template-card').first().click()
 await staticPage.waitForURL('**/business-card-front.svg')
 assert.equal(await staticPage.locator('svg').count(),1)
 await staticContext.close()
 await writeFile(resolve(out,'firefox-qa.json'),JSON.stringify({browser:'Firefox',offline:true,gallery:36,ads:6,pngExport:'1080 x 1080 expected; verified separately',customZip:true,mobileOverflow:false,modalEscape:true,modalFocusTrap:true,pageErrors:errors},null,2))
 console.log('PASS: all 36 visual previews, gallery without JavaScript, fingerprinted editor, mobile widths, rebranding, PNG/SVG/ZIP downloads, Escape, focus trap and guide. No page errors.')
}finally{await browser.close()}
